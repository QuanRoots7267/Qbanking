package com.qbanking.dao;

import com.qbanking.model.Account;
import com.qbanking.model.ChequeAccount;
import com.qbanking.model.Customer;
import com.qbanking.model.InvestmentAccount;
import com.qbanking.model.Role;
import com.qbanking.model.SavingsAccount;
import com.qbanking.model.Transaction;
import com.qbanking.model.TransactionType;
import com.qbanking.model.User;
import com.qbanking.util.PasswordHasher;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

/**
 * Runs once when the program starts:
 *  1. creates the tables if they do not exist yet (the database schema)
 *  2. if the database is empty, inserts the sample data (10 customers + 1 staff user)
 */
public final class DatabaseInitializer {

    public static final String SAMPLE_PASSWORD = "Password@1";
    public static final String STAFF_USERNAME = "staff";
    public static final String STAFF_PASSWORD = "Staff@123";

    private DatabaseInitializer() {
    }

    public static void initialise() {
        Database.inTransaction(connection -> {
            createTables(connection);
            if (new CustomerDAO(connection).count() == 0) {
                insertSampleData(connection);
            }
            return null;
        });
    }

    // ------------------------------------------------------------------ schema

    private static void createTables(Connection connection) throws SQLException {
        try (Statement statement = connection.createStatement()) {

            statement.execute("""
                    CREATE TABLE IF NOT EXISTS customers (
                        id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        first_name VARCHAR(50)  NOT NULL,
                        surname    VARCHAR(50)  NOT NULL,
                        address    VARCHAR(200) NOT NULL
                    )""");

            statement.execute("""
                    CREATE TABLE IF NOT EXISTS users (
                        id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        username      VARCHAR(30)  NOT NULL UNIQUE,
                        password_hash VARCHAR(255) NOT NULL,
                        role          VARCHAR(10)  NOT NULL,
                        customer_id   BIGINT NULL,
                        FOREIGN KEY (customer_id) REFERENCES customers(id)
                    )""");

            // An account always belongs to a customer: customer_id is NOT NULL + a foreign key.
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS accounts (
                        account_number   BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000001) PRIMARY KEY,
                        account_type     VARCHAR(12)   NOT NULL,
                        branch           VARCHAR(60)   NOT NULL,
                        balance          DECIMAL(15,2) NOT NULL,
                        customer_id      BIGINT        NOT NULL,
                        employer_name    VARCHAR(100)  NULL,
                        employer_address VARCHAR(200)  NULL,
                        FOREIGN KEY (customer_id) REFERENCES customers(id)
                    )""");

            statement.execute("""
                    CREATE TABLE IF NOT EXISTS transactions (
                        id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        account_number BIGINT        NOT NULL,
                        type           VARCHAR(12)   NOT NULL,
                        amount         DECIMAL(15,2) NOT NULL,
                        balance_after  DECIMAL(15,2) NOT NULL,
                        description    VARCHAR(200)  NOT NULL,
                        created_at     TIMESTAMP     NOT NULL,
                        FOREIGN KEY (account_number) REFERENCES accounts(account_number)
                    )""");
        }
    }

    // ------------------------------------------------------------- sample data

    private record Person(String firstName, String surname, String address, String username, String branch) {
    }

    private record Employer(String name, String address) {
    }

    private static void insertSampleData(Connection connection) throws SQLException {
        CustomerDAO customerDAO = new CustomerDAO(connection);
        UserDAO userDAO = new UserDAO(connection);
        AccountDAO accountDAO = new AccountDAO(connection);
        TransactionDAO transactionDAO = new TransactionDAO(connection);

        List<Person> people = List.of(
                new Person("Masego", "Wame", "Plot 1021, Broadhurst, Gaborone", "masego", "Gaborone Main"),
                new Person("Kabelo", "Mosweu", "Block 6, Francistown", "kabelo", "Francistown"),
                new Person("Neo", "Kgosi", "Plot 455, Maun", "neo", "Maun"),
                new Person("Lesedi", "Molefe", "Plot 88, Palapye", "lesedi", "Palapye"),
                new Person("Tshepo", "Seretse", "Lobatse Extension 3", "tshepo", "Lobatse"),
                new Person("Boitumelo", "Dube", "Plot 12, Mogoditshane", "boitumelo", "Gaborone Main"),
                new Person("Thabo", "Modise", "Block 9, Gaborone", "thabo", "Gaborone Main"),
                new Person("Naledi", "Sebego", "Plot 730, Kasane", "naledi", "Maun"),
                new Person("Kagiso", "Motsumi", "Ward 4, Serowe", "kagiso", "Palapye"),
                new Person("Lorato", "Tau", "Plot 61, Tlokweng", "lorato", "Gaborone Main"));

        List<Employer> employers = List.of(
                new Employer("Kalahari Logistics (Pty) Ltd", "Plot 100, Gaborone"),
                new Employer("Okavango Foods", "Industrial Site, Francistown"),
                new Employer("Thutong Primary School", "Main Road, Palapye"));

        String sampleHash = PasswordHasher.hash(SAMPLE_PASSWORD); // same password for all sample users

        for (int i = 0; i < people.size(); i++) {
            Person person = people.get(i);

            Customer customer = new Customer(person.firstName(), person.surname(), person.address());
            customerDAO.insert(customer);
            userDAO.insert(new User(0, person.username(), sampleHash, Role.CUSTOMER, customer.getId()));

            // Everyone gets a Savings account...
            Account savings = new SavingsAccount(customer, person.branch(), new BigDecimal(1000 + i * 500));
            save(accountDAO, transactionDAO, savings, "Opening deposit");
            save(transactionDAO, savings.deposit(new BigDecimal("250.00")));
            accountDAO.updateBalance(savings);

            // ...every second customer also gets an Investment account...
            if (i % 2 == 0) {
                Account investment = new InvestmentAccount(customer, person.branch(), new BigDecimal(1000 + i * 250));
                save(accountDAO, transactionDAO, investment, "Opening deposit");
                save(transactionDAO, investment.withdraw(new BigDecimal("100.00")));
                accountDAO.updateBalance(investment);
            }

            // ...and every third customer also has a job, so gets a Cheque account.
            if (i % 3 == 0) {
                Employer employer = employers.get((i / 3) % employers.size());
                Account cheque = new ChequeAccount(customer, person.branch(), new BigDecimal("3500.00"),
                        employer.name(), employer.address());
                save(accountDAO, transactionDAO, cheque, "Opening deposit");
                save(transactionDAO, cheque.deposit(new BigDecimal("8000.00"), "Salary"));
                save(transactionDAO, cheque.withdraw(new BigDecimal("1200.00")));
                accountDAO.updateBalance(cheque);
            }
        }

        // The bank employee who runs the monthly interest payment.
        userDAO.insert(new User(0, STAFF_USERNAME, PasswordHasher.hash(STAFF_PASSWORD), Role.STAFF, 0));
    }

    /** Saves a new account and records its opening-deposit transaction. */
    private static void save(AccountDAO accountDAO, TransactionDAO transactionDAO,
                             Account account, String description) throws SQLException {
        accountDAO.insert(account);
        if (account.getBalance().signum() > 0) {
            transactionDAO.insert(new Transaction(account.getAccountNumber(), TransactionType.DEPOSIT,
                    account.getBalance(), account.getBalance(), description));
        }
    }

    private static void save(TransactionDAO transactionDAO, Transaction transaction) throws SQLException {
        transactionDAO.insert(transaction);
    }
}
